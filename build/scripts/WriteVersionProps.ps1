#Requires -Version 7.4

<#
.SYNOPSIS
Writes the assembly versions a package build stamps, as a Version.g.props file in each package project folder.

.DESCRIPTION
src/Directory.Build.targets imports Version.g.props when it exists.  The file is generated and git-ignored.

The package being built gets its AssemblyVersion, FileVersion and InformationalVersion.  Every other package gets its
AssemblyVersion only, so a dependency built from source in the same solution filter carries its own released assembly
version.  A version that is unknown, such as for a package that has never been released, is left out, and a package with
none gets no file.  This reproduces the Azure DevOps version-stamping steps.
#>
param (
    [Parameter(Mandatory)]
    [ValidateNotNullOrEmpty()]
    [string]    $PackageName,

    # Base64 JSON version records, the 'versions' output of ResolveVersionNumbers.ps1.
    [Parameter()]
    [string]    $EncodedPackageVersions = $env:VERSIONS,

    [Parameter()]
    [string]    $RepositoryRoot,

    [Parameter()]
    [int]   $TraceLevel = 0
)

$ErrorActionPreference = 'Stop'

Import-Module (Join-Path $PSScriptRoot '../psmodules/CommonHelpers/CommonHelpers.psm1') -Scope Local
Import-Module (Join-Path $PSScriptRoot '../psmodules/VersionNumbers/VersionNumbers.psm1') -Scope Local

if (0 -lt $TraceLevel) {
    Set-PSDebug -Trace $TraceLevel
}

if ([string]::IsNullOrEmpty($EncodedPackageVersions)) {
    throw 'No package versions supplied: pass -EncodedPackageVersions or set VERSIONS.'
}
if ([string]::IsNullOrEmpty($RepositoryRoot)) {
    $RepositoryRoot = Get-RepositoryRoot
}

$packageInfo = Get-PackageInfo
if (-not ($packageInfo | Where-Object -Property packageName -EQ -Value $PackageName)) {
    throw "Package information not found for $PackageName."
}
$versionsList = @(ConvertFrom-EncodedVersionList -EncodedValue $EncodedPackageVersions)

foreach ($package in $packageInfo) {
    $versions = $versionsList | Where-Object -Property PackageName -EQ -Value $package.packageName | Select-Object -First 1
    $properties = [ordered]@{}
    if ($null -ne $versions) {
        $properties['AssemblyVersion'] = $versions.AssemblyProductionVersion
        if ($package.packageName -eq $PackageName) {
            $properties['FileVersion'] = $versions.AssemblyProductionFileVersion
            $properties['InformationalVersion'] = $versions.AssemblyProductionInformationalVersion
        }
    }

    $propsPath = Join-Path $RepositoryRoot $package.packageSourcePath 'Version.g.props'
    $lines = foreach ($name in $properties.Keys) {
        if ([string]::IsNullOrEmpty($properties[$name])) {
            Write-Verbose "No $name for $($package.packageName)."
            continue
        }
        # Every value must be a version number; anything else would end up verbatim in the assembly.
        [version]$value = $properties[$name]
        "    <$name>$value</$name>"
    }

    if (-not $lines) {
        Remove-Item -LiteralPath $propsPath -Force -ErrorAction SilentlyContinue
        if ($package.packageName -eq $PackageName) {
            Write-Warning "No assembly versions known for $PackageName; its build is not stamped."
        }
        continue
    }

    if (-not (Test-Path -LiteralPath (Split-Path $propsPath -Parent) -PathType Container)) {
        throw "Package folder $($package.packageSourcePath) not found."
    }

    $content = @(
        '<!-- Generated by build/scripts/WriteVersionProps.ps1.  Do not edit or commit. -->'
        '<Project>'
        '  <PropertyGroup>'
        $lines
        '  </PropertyGroup>'
        '</Project>'
    ) -join "`n"
    [System.IO.File]::WriteAllText($propsPath, "$content`n", [System.Text.UTF8Encoding]::new($false))
    Write-Information "Stamping $($package.packageName): $(($lines | ForEach-Object { $_.Trim() }) -join ' ')"
}
