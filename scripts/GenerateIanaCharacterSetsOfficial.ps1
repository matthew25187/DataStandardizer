#Requires -Version 7.4

<#
    .SYNOPSIS
    Generates the source code of the MimeCharsetRegistry type from the IANA Character Sets registry.

    .DESCRIPTION
    Generates an internal static class holding every name and alias registered in the IANA Character Sets registry
    that is a valid mime-charset name (RFC 2978 §2.3), compared case-insensitively.  Names that are not valid
    mime-charset names, such as ANSI_X3.4-1968 and ISO_8859-1:1987, are left out, as a MimeCharset can't hold them.

    The source is the XML form of the registry, character-sets.xml, whose date of last update is written into the
    generated source.  Generation fails, rather than emitting bad data, where the file isn't the Character Sets
    registry or a record has no name.

    The source code is written to the output stream, so that it can be reviewed before it is redirected to its file.
    The script never writes to a file itself.  The source code needs no further editing.

    .PARAMETER SourceFilePath
    Path to character-sets.xml.

    .PARAMETER SourceCodeTypeName
    Name of the type in the generated source code.

    .EXAMPLE
    ./scripts/GenerateIanaCharacterSetsOfficial.ps1 -SourceFilePath ~/character-sets.xml > src/DataStandardizer.Communication/Mime/MimeCharsetRegistry.cs
#>
[CmdletBinding()]
param (
    [Parameter(Mandatory, HelpMessage = 'Path to the XML form of the IANA Character Sets registry, character-sets.xml.')]
    [string]    $SourceFilePath,

    [Parameter(HelpMessage = 'Name of the type in the generated source code.')]
    [ValidateNotNullOrWhiteSpace()]
    [string]    $SourceCodeTypeName = 'MimeCharsetRegistry'
)

$ErrorActionPreference = 'Stop'

# mime-charset = 1*mime-charset-chars (RFC 2978 §2.3)
$mimeCharsetPattern = '^[A-Za-z0-9!#$%&''+\-^_`{}~]+$'

if (-not (Test-Path -Path $SourceFilePath)) {
    throw "Source file $SourceFilePath not found."
}

$document = [System.Xml.XmlDocument]::new()
$document.Load((Resolve-Path -Path $SourceFilePath).ProviderPath)

$namespaces = [System.Xml.XmlNamespaceManager]::new($document.NameTable)
$namespaces.AddNamespace('r', 'http://www.iana.org/assignments')

$registry = $document.SelectSingleNode("/r:registry[@id='character-sets']", $namespaces)
if ($null -eq $registry) {
    throw "$SourceFilePath is not the IANA Character Sets registry."
}

$updated = $registry.SelectSingleNode('r:updated', $namespaces).InnerText.Trim()
$records = $registry.SelectNodes("r:registry[@id='character-sets-1']/r:record", $namespaces)
if ($records.Count -eq 0) {
    throw "$SourceFilePath has no character sets."
}

$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('//------------------------------------------------------------------------------')
[void]$builder.AppendLine('// <auto-generated>')
[void]$builder.AppendLine("//     This code was generated by scripts/GenerateIanaCharacterSetsOfficial.ps1 from the IANA Character Sets")
[void]$builder.AppendLine("//     registry, last updated $updated.")
[void]$builder.AppendLine('//')
[void]$builder.AppendLine('//     Changes to this file may cause incorrect behavior and will be lost if')
[void]$builder.AppendLine('//     the code is regenerated.')
[void]$builder.AppendLine('// </auto-generated>')
[void]$builder.AppendLine('//------------------------------------------------------------------------------')
[void]$builder.AppendLine()
[void]$builder.AppendLine('using System;')
[void]$builder.AppendLine('using System.Collections.Generic;')
[void]$builder.AppendLine()
[void]$builder.AppendLine('namespace DataStandardizer.Communication.Mime')
[void]$builder.AppendLine('{')
[void]$builder.AppendLine('    /// <summary>')
[void]$builder.AppendLine('    /// The names and aliases registered in the IANA Character Sets registry that are valid <c>mime-charset</c> names (RFC 2978 §2.3).')
[void]$builder.AppendLine('    /// </summary>')
[void]$builder.AppendLine("    internal static class $SourceCodeTypeName")
[void]$builder.AppendLine('    {')
[void]$builder.AppendLine('        /// <summary>')
[void]$builder.AppendLine('        /// Gets the names, compared case-insensitively (RFC 2978 §2.3).')
[void]$builder.AppendLine('        /// </summary>')
[void]$builder.AppendLine('        internal static readonly HashSet<string> Names = new HashSet<string>(StringComparer.OrdinalIgnoreCase)')
[void]$builder.AppendLine('        {')

foreach ($record in $records) {
    $nameNode = $record.SelectSingleNode('r:name', $namespaces)
    if ($null -eq $nameNode -or [string]::IsNullOrWhiteSpace($nameNode.InnerText)) {
        throw "A record of $SourceFilePath has no name."
    }

    $names = [System.Collections.Generic.List[string]]::new()
    $names.Add($nameNode.InnerText.Trim())
    foreach ($alias in $record.SelectNodes('r:alias', $namespaces)) {
        $names.Add($alias.InnerText.Trim())
    }

    $validNames = @($names | Where-Object { $_ -cmatch $mimeCharsetPattern } | Select-Object -Unique)
    if ($validNames.Count -eq 0) {
        continue
    }

    $quotedNames = $validNames | ForEach-Object { '"' + $_ + '"' }
    [void]$builder.AppendLine("            $($quotedNames -join ', '),")
}

[void]$builder.AppendLine('        };')
[void]$builder.AppendLine('    }')
[void]$builder.AppendLine('}')

Write-Output $builder.ToString().TrimEnd()
